// STATUS: rewritten on 2026-10-19 from `railway config pull` against the live
// project "Clearskies" (production), and checked against the railway SDK
// (npm `railway`, v3.16.0, installed in this directory's package.json). The
// services are named as Railway has them, `clearskies-api-` and
// `clearskies-web`: the previous version named them `api` and `web`, and an
// apply would have created two new services beside the live ones rather than
// managing them.
//
// What this file changes from the dashboard state it was pulled from, and why:
//
//   1. Region. Both services ran in Amsterdam (`ams`) while the database is a
//      Neon branch in AWS us-east-2 (Ohio) and the tile archive is in Neon
//      Object Storage beside it. Every hexagon click made five round trips
//      across the Atlantic. US East (Virginia) is a few milliseconds from
//      Ohio, and it is where the readers are: Louisiana.
//   2. Builder. The dashboard said Railpack and the builds used the
//      Dockerfile only because Railway prefers one when it finds it. Said
//      outright here, so a stray build setting cannot switch it.
//   3. Health checks. A deploy now has to answer before it takes traffic. The
//      API's check is /health, which reaches the database; its timeout allows
//      for a Neon branch waking from scale-to-zero (several seconds, once).
//   4. CDN on `web` only: the bundle's assets are content-hashed and
//      immutable, and index.html is never cached so a deploy is seen at once.
//      Never on `api`: the drafting endpoint returns a document generated per
//      request, and an edge cache in front of it could serve one reader's
//      output to another.
//   5. Two dead variables dropped from `api`: PILOT_STATE (coverage has been
//      read from the scored_state table since migration 0031) and
//      CLEARSKIES_TEST_DATABASE_URL (read only by the test suite).
//   6. DB_CONNECT_TIMEOUT from 5 to 10 seconds, so the first request after
//      the Neon branch has scaled to zero waits for it rather than failing.
//
// Not in this file:
//
//   - Domains. The two *.up.railway.app domains are generated by Railway and
//     must not be written into source; they already exist.
//   - Preview environments. They need a Pro workspace and this project is on
//     Hobby, so reviewers check a branch locally with `make web`.
//
// Secrets and values that already exist are preserve()d: an apply keeps the
// remote value without it ever being written here. Change one in the
// dashboard or with `railway variable set`, not in this file.
//
// Workflow: edit, `railway config plan`, review, `railway config apply`. The
// split repositories carry no railway.json, so this file is the only thing
// that configures the services; Railway stops reading railway.json entirely
// on 2026-12-01.

import { defineRailway, github, preserve, project, service } from "railway/iac";

// One repository per service, generated from this monorepo by
// scripts/split-repos.sh. A change is deployed when the split is pushed, not
// when it is committed here; docs/repos.md is the procedure. The API's slug
// really does end in a hyphen.
const WEB_REPO = "Vele189/clearskies-web";
const API_REPO = "Vele189/clearskies-api-";

// Both split repositories take their default branch from this one, "master".
// The SDK defaults an unspecified branch to "main", which does not exist.
const BRANCH = "master";

// Railway's own hardware in US East (Virginia): the nearest region to the
// Neon branch in us-east-2.
const US_EAST = "us-east4-eqdc4a";

export default defineRailway(() => {
  // Built from the Dockerfile at the root of the api repository. No start
  // command: an IaC start command would override the image's CMD, which is
  // already `uvicorn app.main:app --host 0.0.0.0 --port ${PORT}` in shell form
  // so that the platform's port is expanded.
  const api = service("clearskies-api-", {
    source: github(API_REPO, { branch: BRANCH }),
    build: { builder: "DOCKERFILE", dockerfilePath: "Dockerfile" },
    regions: { [US_EAST]: 1 },
    healthcheck: "/health",
    healthcheckTimeout: 60,
    // Restart on failure is the platform default; capped here so a crash loop
    // gives up rather than redeploying forever.
    deploy: { restartPolicyMaxRetries: 5 },
    env: {
      // The Neon branch's pooled (`-pooler`) and direct connection strings.
      // Migrations are not run from this service: they take a session-level
      // advisory lock, which the pooler's transaction mode does not hold.
      DATABASE_URL: preserve(),
      DATABASE_URL_UNPOOLED: preserve(),
      DB_CONNECT_TIMEOUT: "10",
      // The web service's public origin. Without it the deployed frontend is
      // refused by CORS.
      CORS_ORIGINS: preserve(),
      LOG_LEVEL: preserve(),
      LOG_FORMAT: preserve(),
      READ_RATE_LIMIT: preserve(),
      READ_RATE_WINDOW_S: preserve(),
      // The hard monthly spend cap is set on this key with the provider, in
      // the OpenAI dashboard, not here: a limit the application enforces stops
      // working when the application has a bug. docs/drafting.md section 8.
      OPENAI_API_KEY: preserve(),
      DRAFT_MODEL: preserve(),
      DRAFT_RATE_LIMIT: preserve(),
      DRAFT_RATE_WINDOW_S: preserve(),
      // Pinned to the corpus. Changing it without re-embedding puts vectors
      // from two models in one space. docs/corpus.md section 5.
      EMBEDDING_MODEL: preserve(),
    },
  });

  // A Dockerfile build: `npm ci && npm run build` in a node stage, served by
  // nginx on ${PORT}. VITE_ variables are inlined at build time (the
  // Dockerfile declares an ARG for each), so changing one means a rebuild,
  // not a restart.
  const web = service("clearskies-web", {
    source: github(WEB_REPO, { branch: BRANCH }),
    build: { builder: "DOCKERFILE", dockerfilePath: "Dockerfile" },
    regions: { [US_EAST]: 1 },
    healthcheck: "/",
    healthcheckTimeout: 30,
    // Restart on failure is the platform default; capped here so a crash loop
    // gives up rather than redeploying forever.
    deploy: { restartPolicyMaxRetries: 5 },
    cdn: { enabled: true, htmlCaching: "never" },
    env: {
      PORT: preserve(),
      VITE_API_BASE_URL: preserve(),
      // The PMTiles archive in Neon Object Storage (a public_read bucket on
      // the dev-seed branch), read with Range requests.
      VITE_TILES_URL: preserve(),
      VITE_BASEMAP_STYLE: preserve(),
    },
  });

  return project("Clearskies", { resources: [api, web] });
});
